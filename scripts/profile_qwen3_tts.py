"""Measure the Qwen3-TTS 0.6B Code Predictor ONNX in isolation on ORT CPU."""

import argparse
import hashlib
from io import BytesIO
from pathlib import Path
import tempfile
from urllib.request import urlopen

import numpy as np

from htp_insight.core import Core, atomic_write, encode
from htp_insight.profiles import make_session, output_error

REPO = "romara-labs/Qwen3-TTS-12Hz-0.6B-Base-ONNX"
REVISION = "aee727788cab0154fcf663a9cc1aec2616704eca"
FILES = {
    "code_predictor.onnx": "a310ad365a5b0d3f2b039550f0920965d6b1c944f3ba9873780196c59bb7029c",
    "code_predictor.onnx.data": "342903441233733eb7493c352f0d7f084dba9a7be7c1fcf3874da8dbee38e72f",
}


def fetch(root: Path, host: str):
    root.mkdir(parents=True, exist_ok=True)
    for name, checksum in FILES.items():
        target = root / name
        if target.is_file():
            with target.open("rb") as stream:
                if hashlib.file_digest(stream, "sha256").hexdigest() == checksum:
                    continue
            raise ValueError(f"SHA-256 mismatch in existing {target}")
        with tempfile.NamedTemporaryFile(dir=root, delete=False) as stream:
            partial = Path(stream.name)
            try:
                expected = hashlib.sha256()
                url = f"https://{host}/{REPO}/resolve/{REVISION}/{name}?download=true"
                with urlopen(url, timeout=45) as response:
                    for block in iter(lambda: response.read(1024 * 1024), b""):
                        expected.update(block)
                        stream.write(block)
                if expected.hexdigest() != checksum:
                    raise ValueError(f"SHA-256 mismatch while downloading {name}")
                stream.close()
                partial.replace(target)
            finally:
                partial.unlink(missing_ok=True)


def prepare_decode(model: Path):
    rng = np.random.default_rng(7)
    session = make_session(model)
    empty = np.empty((5, 1, 8, 0, 128), dtype=np.float32)
    _, key, value = session.run(["logits", "present_keys", "present_values"], {
        "inputs_embeds": rng.normal(0, .1, (1, 2, 1024)).astype(np.float32),
        "generation_steps": np.array([0], dtype=np.int64), "past_keys": empty, "past_values": empty,
    })
    inputs = {"inputs_embeds": rng.normal(0, .1, (1, 1, 1024)).astype(np.float32),
              "generation_steps": np.array([1], dtype=np.int64), "past_keys": key, "past_values": value}
    names = [output.name for output in session.get_outputs()]
    reference = dict(zip(names, session.run(names, inputs)))
    if reference["logits"].shape != (1, 1, 2048):
        raise ValueError("Unexpected decode logits shape")
    for tensor in ("keys", "values"):
        result = reference[f"present_{tensor}"]
        before = inputs[f"past_{tensor}"]
        if result.shape != (5, 1, 8, 3, 128) or not np.array_equal(result[:, :, :, :-1, :], before):
            raise ValueError(f"Unexpected KV-cache update for {tensor}")
    return inputs, reference


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mirror", action="store_true", help="Download the same pinned files from hf-mirror.com")
    parser.add_argument("--repeats", type=int, default=50)
    args = parser.parse_args()
    if not 2 <= args.repeats <= 1000:
        parser.error("--repeats must be between 2 and 1000")
    core = Core()
    folder = core.inbox / "qwen3-tts-0.6b"
    fetch(folder, "hf-mirror.com" if args.mirror else "huggingface.co")
    model = folder / "code_predictor.onnx"
    print("Verified pinned Code Predictor files", flush=True)
    inputs, reference = prepare_decode(model)
    sample = folder / "decode-step-1.npz"
    buffer = BytesIO()
    np.savez(buffer, **inputs)
    atomic_write(sample, buffer.getvalue())
    origin = f"https://huggingface.co/{REPO}/blob/{REVISION}/{model.name}"
    artifact = core.import_model(str(model.relative_to(core.inbox)), name="Qwen3-TTS 12Hz 0.6B · Code Predictor", origin=origin)["artifact"]
    print("Registered", artifact["id"], flush=True)
    profile = core.run_ort_profile(artifact["id"], str(sample.relative_to(core.inbox)), warmup=10,
                                   repeats=args.repeats, trace_runs=3)
    with np.load(core.item(profile["id"], "outputs.npz"), allow_pickle=False) as outputs:
        numeric = output_error(reference, dict(outputs))
    if not numeric["passed"]:
        raise ValueError("Code Predictor post-import output disagrees with the original ONNX")
    result = {"artifact": artifact, "profile": profile, "numeric": numeric,
              "input_origin": "Deterministic synthetic embeddings; KV cache generated by real model prefill",
              "source_sha256": FILES, "hotspots": core.get_hotspots(profile["id"], limit=5)}
    output = core.root / "qwen3-tts-code-predictor.json"
    atomic_write(output, encode(result))
    print(output)


if __name__ == "__main__":
    main()
